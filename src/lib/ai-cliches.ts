/**
 * 诊断模式用：完整清单。要求 < 600 字，防止提示词膨胀推高 token 成本。
 * 分 6 组，对照 31 条上游模式做小说场景裁剪。
 */
export const CLICHE_CHECKLIST = `A. 铺垫代替陈述
- 假对比：「不是X，而是Y」「不仅……更是……」，抬高语气的对仗
- 戏剧性碎片：连续超短句制造悬念（「他停了。回头。」）
- 伪深度格言：脱离情节的格言式总结
- 起跑式铺垫：「殊不知」「然而他不知道的是」等预告式过渡

B. 公式化节奏
- 强凑三段式：为对仗凑出的三连排比（「他冷静、果断、狠辣」）
- 句式开头复读：连续多句同一开头（「他……他……他……」）
- 破折号滥用、限定词堆叠（似乎仿佛好像）
- 段落长度过度均匀，像模板填充

C. 拔高与借权威
- AI/公文高频词：赋能、闭环、至关重要、无缝、深入探讨
- 网文程式化反应：不由得、心中一震、瞳孔骤缩、深吸一口气
- 意义拔高：「标志着……的时代」「注定不平凡」
- 句尾拔高：「彰显了……」「诠释了……」
- 宣传腔与不具名权威：堪称、被誉为，却无具体来源

D. 排版（仅作者说明类文字，正文不做主检项）
- 装饰性粗体、表情符号、箭头当结构

E. 聊天与草稿残留
- 客服腔（「好问题」）、免责复读（「需要注意的是」）、谈论上一稿

F. 中文特有
- 层叠的「的」：长定语套娃
- 「进行＋动词」冗长：「进行全面检查」→「全面检查」
- 被字句堆叠，掩盖施事者
- 四字词空泛排比，成语连用但无信息
- 套话收尾：总而言之、让我们拭目以待、一切才刚刚开始

判定边界：命中且空泛、重复或与文体不符才报告；作者有意的强调、
真实的不确定、刻意的短句节奏，一律保留，不因模式命中而删改。`;

